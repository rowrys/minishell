#include "libft.h"

size_t	ft_strlcat(char *dst, const char *src, size_t size)
{
	size_t	size_d;
	size_t	size_s;

	size_d = ft_strnlen(dst, size);
	size_s = ft_strlcpy(dst + size_d, src, size - size_d);
	return (size_d + size_s);
}
