#include "libft.h"

void	ft_free_double(char ***ptr)
{
	int	i;

	i = 0;
	while (ptr && *ptr && (*ptr)[i])
	{
		free((*ptr)[i]);
		(*ptr)[i] = NULL;
		i++;
	}
	free(*ptr);
	*ptr = NULL;
}
